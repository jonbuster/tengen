ALTER TABLE rules ADD CONSTRAINT fk_rules_notification_template
    FOREIGN KEY (notification_template_id) REFERENCES notification_templates(id);

CREATE INDEX idx_notification_destinations_channel_enabled
    ON notification_destinations (channel, enabled, display_name);
CREATE INDEX idx_notification_templates_channel_active
    ON notification_templates (channel, active, name, version);
